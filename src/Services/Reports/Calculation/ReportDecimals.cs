namespace SnowMeltingCalculator.Services.Reports.Calculation
{
    /// <summary>
    /// Таблица «единица → знаки» для табличных величин ПЗ (В9, план P1,
    /// спека §7.3): шт/контур → 0; мм/Вт/Па → 0; м/°C/м² → 1; кВт/м³/ч/л → 2;
    /// Re → 0; скорость → 2. Единицы вне таблицы (λ/R/ν/σ и составные
    /// теплотехнические) сохраняют текущую точность N3 — «не ухудшать».
    /// Числовые величины с единицей «-» (Re, λ, ηR, Kv) получают знаки
    /// явно в билдерах, потому что единица их не различает.
    /// </summary>
    public static class ReportDecimals
    {
        /// <summary>Знаки после разделителя для табличного вывода величины с единицей <paramref name="unit"/>.</summary>
        public static int For(string unit)
        {
            return unit switch
            {
                // Таблица §7.3: шт/контур → 0.
                "шт" => 0,
                // мм → 0 (длины в миллиметрах); см — семейство длины.
                "мм" => 0,
                "см" => 0,
                // Вт → 0; Па → 0 (и семейство Па/м).
                "Вт" => 0,
                "Па" => 0,
                "Па/м" => 0,
                // м/°C/м² → 1; K — семейство температур.
                "м" => 1,
                "м²" => 1,
                "°C" => 1,
                "K" => 1,
                // кВт/м³/ч/л → 2; кПа — кило-масштаб, л/ч и л/(ч·м²) —
                // семейство расхода, м/с — скорость.
                "кВт" => 2,
                "кПа" => 2,
                "м³/ч" => 2,
                "л" => 2,
                "л/ч" => 2,
                "л/(ч·м²)" => 2,
                "м/с" => 2,
                // Обороты клапана — четвертные доли; численный формат
                // запасной, рендер выводит дробью (¼/½/¾).
                "об" => 0,
                "об." => 0,
                // λ/R/ν/σ и единицы вне таблицы — текущие N3 (не ухудшать).
                _ => 3,
            };
        }
    }
}
