namespace SnowMeltingCalculator.Models.Climate
{
    /// <summary>
    /// Климатическая зона для выбора мощности системы снеготаяния
    /// Определяется по температуре холодной пятидневки (t_5days_092)
    /// </summary>
    public enum ClimateZone
    {
        /// <summary>
        /// Зона M10: t_5days_092 ≥ -27°C
        /// Используется колонка -10°C в таблицах РЕХАУ
        /// </summary>
        Zone_M10 = 0,

        /// <summary>
        /// Зона M15: -37°C < t_5days_092 < -27°C
        /// Используется колонка -15°C в таблицах РЕХАУ
        /// </summary>
        Zone_M15 = 1,

        /// <summary>
        /// Зона M20: t_5days_092 ≤ -37°C
        /// Используется колонка -20°C в таблицах РЕХАУ
        /// </summary>
        Zone_M20 = 2,

        /// <summary>
        /// Зона M20 Plus: Повышенные требования
        /// Принудительно используется колонка -20°C в таблицах РЕХАУ
        /// </summary>
        Zone_M20_Plus = 3
    }
}